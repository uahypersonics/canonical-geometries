# --------------------------------------------------
# registry: one entry per `geometry <type>` command group
# --------------------------------------------------
@dataclass(frozen=True, slots=True)
class GeometryCommand:
    """What one `geometry <type>` command group shows and writes.

    Attributes:
        help: One-line description shown in `geometry --help`.
        template: Starter configuration written by `geometry <type> init`.
    """

    help: str
    template: str


# keys are the command names and must match the [geometry] type values in config.py
GEOMETRY_COMMANDS: dict[str, GeometryCommand] = {
    "plate": GeometryCommand(
        help="Flat plate with a circular leading edge.",
        template=PLATE_TEMPLATE,
    ),
    "wedge": GeometryCommand(
        help="Planar blunted wedge: circular nose plus a straight body.",
        template=WEDGE_TEMPLATE,
    ),
    "cone": GeometryCommand(
        help="Sphere-cone (axisymmetric); writes its meridian.",
        template=CONE_TEMPLATE,
    ),
}
