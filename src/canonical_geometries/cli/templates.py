"""Starter configurations and help text for each `geometry <type>` command group.

Each template below is exactly the file `geometry <type> init` writes. The
[points] and [output] tables repeat on purpose: every template reads as a
complete, standalone file.
"""

# --------------------------------------------------
# load necessary modules
# --------------------------------------------------
from __future__ import annotations

from dataclasses import dataclass

# --------------------------------------------------
# starter configurations
# --------------------------------------------------
PLATE_TEMPLATE = """\
# Generated by: geometry plate init
# Edit this file, then run: geometry plate run plate.toml

# Flat plate with a circular leading edge (upper half).
# Stagnation point at the origin, x downstream, y up.
[geometry]
# type marker
type = "plate"
# nose radius in [m]
nose_radius = 100.0e-6
# length of flat plate, measured from nose tip in [m]
length = 0.5

# Points per piece, each count including both ends of the piece. The junction
# is always a sample point; nose points are equally spaced in angle.
[points]
# number of points on the nose arc (91 = 1 deg steps on the 90 deg arc)
n_nose = 91
# number of points on the flat part of the plate
n_body = 200

# The path is relative to this file.
[output]
# moldline file: .csv, or .dat for Tecplot ASCII
# columns: x, y, z, s in [m]; nx, ny, nz; curvature in [1/m]
file = "plate.csv"
"""

